#!/bin/sh
# Builds the WebAssembly game and embeds it into web/rustcraft_wasm.js so that
# web/index.html also works when opened straight from disk.
#
# Needs: a Rust toolchain with the wasm32-unknown-unknown target, a C++ compiler that can
# target wasm32 (zig or clang), and python3 for the base64 step.
set -eu
cd "$(dirname "$0")/.."
cargo rustc --lib --release --target wasm32-unknown-unknown --crate-type cdylib "$@"
WASM=target/wasm32-unknown-unknown/release/rustcraft.wasm
python3 - "$WASM" web/rustcraft_wasm.js <<'PY'
import base64, sys
data = open(sys.argv[1], 'rb').read()
with open(sys.argv[2], 'w') as out:
    out.write('// Generated by tools/build-web.sh - the game compiled to WebAssembly, base64 encoded.\n')
    out.write('const RUSTCRAFT_WASM = "' + base64.b64encode(data).decode() + '";\n')
print(f'{sys.argv[2]}: {len(data)} bytes of WebAssembly embedded')
PY
